const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  getConfig: () => ipcRenderer.invoke('config:get'),
  setConfig: (partial) => ipcRenderer.invoke('config:set', partial),
  getScreen: () => ipcRenderer.invoke('screen:get'),
  setIgnore: (ignore) => ipcRenderer.send('pet:ignore', ignore),
  showTodo: () => ipcRenderer.send('todo:show'),
  hideTodo: () => ipcRenderer.send('todo:hide'),
  minimizeTodo: () => ipcRenderer.send('todo:minimize'),
  togglePin: () => ipcRenderer.invoke('todo:togglePin'),
  setupDone: () => ipcRenderer.send('setup:done'),
  setupCancel: () => ipcRenderer.send('setup:cancel'),
  quit: () => ipcRenderer.send('app:quit'),
  petMenu: () => ipcRenderer.send('pet:menu'),
  openReport: (auto) => ipcRenderer.send('report:open', !!auto),
  closeReport: () => ipcRenderer.send('report:close'),
  pomo: (cmd) => ipcRenderer.send('pomo:cmd', cmd),
  onPomoCmd: (cb) => ipcRenderer.on('pomo:cmd', (_e, cmd) => cb(cmd)),
  onIdleAway: (cb) => ipcRenderer.on('idle:away', (_e, d) => cb(d)),
  onIdleBack: (cb) => ipcRenderer.on('idle:back', () => cb()),
  onProfileChanged: (cb) => ipcRenderer.on('profile:changed', () => cb()),
  onConfigChanged: (cb) => ipcRenderer.on('config:changed', (_e, cfg) => cb(cfg)),
  onTodoShown: (cb) => ipcRenderer.on('todo:shown', () => cb()),
  listScreens: () => ipcRenderer.invoke('screen:list'),
  onScreenChanged: (cb) => ipcRenderer.on('screen:changed', (_e, info) => cb(info)),
  log: (src, msg) => ipcRenderer.send('log:write', src, msg),
  openLog: () => ipcRenderer.send('log:open'),
  petAlive: () => ipcRenderer.send('pet:alive'),
  focusPet: () => ipcRenderer.send('pet:focus'),
  setYielded: (v) => ipcRenderer.send('pet:yielded', !!v),
  composeNote: (to) => ipcRenderer.send('note:compose', to || null),
  onComposeNote: (cb) => ipcRenderer.on('note:compose', (_e, to) => cb(to)),
});
